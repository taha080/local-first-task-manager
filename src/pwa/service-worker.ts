/**
 * Builds the classic (non-module) service worker shipped as `dist/sw.js`.
 * Keeping the worker as generated text lets the precache list include Vite's
 * hashed asset names without a second bundler.
 */

export function renderServiceWorker(options: {
  cacheName: string;
  base: string;
  precacheUrls: readonly string[];
}): string {
  const base = options.base.endsWith('/') ? options.base : `${options.base}/`;
  const indexUrl = `${base}index.html`;

  return `/* Generated by the Vite build. Do not edit dist/sw.js by hand.
 * This worker is served at ${base}sw.js. Its scope is that directory, so it
 * controls the GitHub Pages project and does not intercept other sites
 * hosted on the same origin.
 */
const CACHE_NAME = ${JSON.stringify(options.cacheName)};
const BASE = ${JSON.stringify(base)};
const INDEX_URL = ${JSON.stringify(indexUrl)};
const PRECACHE_URLS = ${JSON.stringify([...options.precacheUrls], null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    precache().then(() => {
      self.skipWaiting();
    }),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key.startsWith('lftm-') && key !== CACHE_NAME)
            .map((key) => caches.delete(key)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  // Other project sites share this GitHub Pages origin. Leave them alone.
  if (!url.pathname.startsWith(BASE)) return;

  if (request.mode === 'navigate') {
    event.respondWith(networkFirstNavigation(request));
    return;
  }

  event.respondWith(cacheFirst(request));
});

async function precache() {
  const cache = await caches.open(CACHE_NAME);
  await cache.addAll(PRECACHE_URLS);
  // The site root is the directory URL, which is not a file in dist.
  // Store that request under the same body as index.html so an offline
  // reload of the Pages URL still opens the app.
  const index = await cache.match(INDEX_URL);
  if (index) await cache.put(BASE, index.clone());
}

async function networkFirstNavigation(request) {
  try {
    const response = await fetch(request);
    if (response.ok) {
      const cache = await caches.open(CACHE_NAME);
      await cache.put(request, response.clone());
    }
    return response;
  } catch (error) {
    const cached = await caches.match(request);
    if (cached) return cached;
    const index = await caches.match(INDEX_URL);
    if (index) return index;
    const scopeDocument = await caches.match(BASE);
    if (scopeDocument) return scopeDocument;
    throw error;
  }
}

async function cacheFirst(request) {
  const cached = await caches.match(request);
  if (cached) return cached;

  const response = await fetch(request);
  if (response.ok) {
    const cache = await caches.open(CACHE_NAME);
    await cache.put(request, response.clone());
  }
  return response;
}
`;
}
